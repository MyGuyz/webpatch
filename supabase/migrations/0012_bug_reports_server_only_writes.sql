-- ปิดช่องให้เบราว์เซอร์เขียนตรงเข้า bug_reports / บักเก็ต bug-reports เอง (ดู ADR-013)
--
-- เดิม insert เปิดให้ anon/authenticated ยิงตรงจากเบราว์เซอร์ได้เลย (0001, 0003) โดยตั้งใจให้คน
-- แจ้งบั๊กได้โดยไม่ต้องล็อกอิน แต่นั่นแปลว่าใครก็เรียก Supabase JS SDK/REST ข้าม UI ของเว็บไป
-- ตรงๆ ได้ ทำให้ตัวกันสแปม (/api/bug-report-guard เดิม) เป็นแค่คำขอความร่วมมือฝั่งเบราว์เซอร์
-- ที่เลือกจะเชื่อหรือไม่ก็ได้ ไม่ใช่การบังคับจริง — ใครก็ส่งรายงานปลอมหรืออัปโหลดไฟล์รัวๆ
-- ได้ไม่จำกัด เสี่ยงกินโควตา Storage ของ Supabase จนเว็บทั้งเว็บกระทบ
--
-- ตอนนี้การส่งรายงานบั๊ก (ตรวจฟอร์ม + กันสแปม + อัปโหลดไฟล์แนบ + insert แถว) ย้ายไปทำที่
-- /api/bug-report-submit ฝั่งเซิร์ฟเวอร์ทั้งหมด ใช้ service role key ซึ่งข้าม RLS อยู่แล้ว
-- จึงไม่ต้องมี policy insert ให้ anon/authenticated อีกต่อไป — ปิดสองอันนี้เพื่อไม่ให้มีทาง
-- เขียนตรงเหลืออยู่เลยแม้แต่ทางเดียว

drop policy "ส่งรายงานบั๊กได้" on bug_reports;
drop policy "แนบไฟล์บั๊กได้" on storage.objects;
